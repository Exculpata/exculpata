#!/usr/bin/env python3
"""Generate or check documentation and QA names from the rename contract."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from case_intelligence.legacy_names import LEGACY_STEM, NAME_CONTRACTS, name_value  # noqa: E402

DOC_START = "<!-- BEGIN GENERATED RENAME CONTRACT -->"
DOC_END = "<!-- END GENERATED RENAME CONTRACT -->"


def qa_environment_source() -> str:
    """Keep the existing current-first, nonempty QA environment lookup."""
    current = json.dumps(name_value("environment", suffix="QA_"))
    legacy = json.dumps(name_value("environment", LEGACY_STEM, suffix="QA_"))
    names = {
        suffix: [
            name_value("environment", suffix="QA_" + suffix),
            name_value("environment", LEGACY_STEM, suffix="QA_" + suffix),
        ]
        for suffix in ("ORIGIN", "ARTIFACTS", "BROWSER_CHANNEL")
    }
    return (
        "/* Generated by scripts/rename_contract_artifacts.py; do not edit. */\n"
        "'use strict';\n"
        f"const currentPrefix = {current};\n"
        f"const legacyPrefix = {legacy};\n"
        f"const names = {json.dumps(names, indent=2)};\n"
        "module.exports = (name) => {\n"
        "  const [current, legacy] = Object.hasOwn(names, name)\n"
        "    ? names[name] : [currentPrefix + name, legacyPrefix + name];\n"
        "  return process.env[current] || process.env[legacy];\n"
        "};\n"
    )


def documentation_block() -> str:
    rows = [
        DOC_START,
        "### Rename contract",
        "",
        "Generated from `src/case_intelligence/legacy_names.py`. Run",
        "`python scripts/rename_contract_artifacts.py --write` after an intentional contract change;",
        "`python scripts/rename_contract_artifacts.py --check` verifies these artifacts in CI.",
        "",
        "Aliases accept the previous name. Generation-specific names preserve an existing",
        "node's coordinates. Retained names stay the same for both generations; they are",
        "not migration targets. Environment aliases prefer a nonempty current value,",
        "while conflicting authentication headers fail closed.",
        "",
        "| Contract | Previous name | Current name | Behavior |",
        "| --- | --- | --- | --- |",
    ]
    for key, contract in sorted(NAME_CONTRACTS.items()):
        rows.append(f"| {key} | `{contract.legacy}` | `{contract.current}` | {contract.behavior} |")
    return "\n".join([*rows, DOC_END]) + "\n"


def updated_documentation(text: str) -> str:
    """Replace exactly one generated block without changing surrounding prose."""
    starts, ends = text.count(DOC_START), text.count(DOC_END)
    if starts == ends == 0:
        return text.rstrip() + "\n\n" + documentation_block()
    if starts != 1 or ends != 1 or text.index(DOC_START) > text.index(DOC_END):
        raise ValueError("rename contract documentation markers are malformed")
    before, remaining = text.split(DOC_START, 1)
    _, after = remaining.split(DOC_END, 1)
    return before + documentation_block().removesuffix("\n") + after


def generated_artifacts(root: Path = ROOT) -> dict[Path, str]:
    document = root / "docs/BRANDING.md"
    return {
        root / "scripts/qa-env.cjs": qa_environment_source(),
        document: updated_documentation(document.read_text(encoding="utf-8")),
    }


def findings(root: Path = ROOT) -> list[str]:
    return [
        path.relative_to(root).as_posix()
        for path, expected in generated_artifacts(root).items()
        if not path.is_file() or path.read_text(encoding="utf-8") != expected
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="update generated artifacts")
    mode.add_argument("--check", action="store_true", help="check artifacts without writing (default)")
    args = parser.parse_args(argv)
    if args.write:
        for path, content in generated_artifacts().items():
            path.write_text(content, encoding="utf-8")
        return 0
    stale = findings()
    if stale:
        print("Rename contract artifacts need regeneration: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Rename contract artifacts match the source table.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
